/**
 * AI-driven Dashboard summary card that displays spending pattern analysis and a personalized
 * daily Financial Tip generated by Firebase AI Logic (Gemini) for the user's debt profile.
 */
@Composable
fun AiDailyFinancialTipCard(
    tipState: DailyAiTipUiState,
    snapshot: SpendingAndDebtSnapshot?,
    currencyUnit: CurrencyUnit,
    privacyMasked: Boolean,
    onRefreshTip: () -> Unit,
    onOpenConnectivityPrivacySettings: () -> Unit = {},
    modifier: Modifier = Modifier
) {
    val ext = LocalTarazinoColors.current
    val isLoading = tipState is DailyAiTipUiState.Loading

    val spinTransition = rememberInfiniteTransition(label = "AiRefreshSpin")
    val spinDegrees by spinTransition.animateFloat(
        initialValue = 0f,
        targetValue = 360f,
        animationSpec = infiniteRepeatable(
            animation = tween(durationMillis = 1000, easing = LinearEasing),
            repeatMode = RepeatMode.Restart
        ),
        label = "AiRefreshAngle"
    )

    val shimmerAlpha by spinTransition.animateFloat(
        initialValue = 0.25f,
        targetValue = 0.65f,
        animationSpec = infiniteRepeatable(
            animation = tween(durationMillis = 850, easing = FastOutSlowInEasing),
            repeatMode = RepeatMode.Reverse
        ),
        label = "AiShimmerAlpha"
    )

    val accentStart = MaterialTheme.colorScheme.primary
    val accentEnd = MaterialTheme.colorScheme.secondary

    Surface(
        shape = RoundedCornerShape(24.dp),
        color = MaterialTheme.colorScheme.surface,
        border = BorderStroke(
            1.15.dp,
            Brush.linearGradient(
                listOf(
                    accentStart.copy(alpha = if (ext.isDark) 0.65f else 0.45f),
                    accentEnd.copy(alpha = if (ext.isDark) 0.50f else 0.35f)
                )
            )
        ),
        shadowElevation = if (ext.isDark) 0.dp else 5.dp,
        modifier = modifier
            .fillMaxWidth()
            .testTag("dashboard_ai_daily_tip_card")
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .background(
                    Brush.verticalGradient(
                        listOf(
                            accentStart.copy(alpha = if (ext.isDark) 0.14f else 0.07f),
                            accentEnd.copy(alpha = if (ext.isDark) 0.06f else 0.03f),
                            Color.Transparent
                        )
                    )
                )
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            // 1. Header: AI Sparkle Emblem + Title + 48dp Refresh Button
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(10.dp),
                    modifier = Modifier.weight(1f)
                ) {
                    Box(
                        contentAlignment = Alignment.Center,
                        modifier = Modifier
                            .size(42.dp)
                            .clip(RoundedCornerShape(14.dp))
                            .background(
                                Brush.linearGradient(
                                    listOf(
                                        accentStart.copy(alpha = 0.24f),
                                        accentEnd.copy(alpha = 0.22f)
                                    )
                                )
                            )
                    ) {
                        Icon(
                            imageVector = Icons.Default.AutoAwesome,
                            contentDescription = "مشاور هوشمند مالی روزانه",
                            tint = accentStart,
                            modifier = Modifier.size(22.dp)
                        )
                    }
                    Column(modifier = Modifier.weight(1f)) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            TarazinoAutoSizeText(
                                text = "نکته مالی روزانه هوشمند",
                                style = MaterialTheme.typography.titleSmall,
                                fontWeight = FontWeight.ExtraBold,
                                color = MaterialTheme.colorScheme.onSurface,
                                maxLines = 1,
                                minFontSize = 11.sp
                            )
                            Surface(
                                shape = RoundedCornerShape(999.dp),
                                color = accentEnd.copy(alpha = 0.18f)
                            ) {
                                Text(
                                    text = "AI",
                                    style = MaterialTheme.typography.labelSmall,
                                    fontWeight = FontWeight.Black,
                                    color = accentEnd,
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 1.dp)
                                )
                            }
                        }
                        Spacer(modifier = Modifier.height(2.dp))
                        val todayLabel = snapshot?.todayJalali?.let {
                            JalaliCalendarEngine.formatJalaliShortText(it)
                        } ?: "امروز"
                        Text(
                            text = "تحلیل الگوی مخارج و پروفایل بدهی • $todayLabel",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis
                        )
                    }
                }

                IconButton(
                    onClick = onRefreshTip,
                    enabled = !isLoading,
                    modifier = Modifier
                        .size(48.dp)
                        .testTag("dashboard_ai_tip_refresh_btn")
                ) {
                    Icon(
                        imageVector = Icons.Default.Refresh,
                        contentDescription = "به‌روزرسانی تحلیل و نکته مالی امروز",
                        tint = accentStart,
                        modifier = Modifier
                            .size(22.dp)
                            .graphicsLayer {
                                rotationZ = if (isLoading) spinDegrees else 0f
                            }
                    )
                }
            }

            // 2. Analyzed Spending & Debt Signal Strip (Real Context Metrics)
            if (snapshot != null) {
                SpendingSignalPillRow(
                    snapshot = snapshot,
                    currencyUnit = currencyUnit,
                    privacyMasked = privacyMasked
                )
            }

            // 3. Dynamic AI Tip State Machine (Idle / Loading / Success / Error)
            AnimatedContent(
                targetState = tipState,
                transitionSpec = { fadeIn(tween(240)) togetherWith fadeOut(tween(160)) },
                label = "DailyAiFinancialTipState"
            ) { state ->
                when (state) {
                    is DailyAiTipUiState.Loading -> {
                        AiTipLoadingSkeleton(shimmerAlpha = shimmerAlpha)
                    }

                    is DailyAiTipUiState.Success -> {
                        AiTipSuccessBody(
                            tip = state.tip,
                            isCachedFromToday = state.isCachedFromToday,
                            profileChangedSinceGeneration = snapshot != null &&
                                state.tip.profileFingerprint.isNotBlank() &&
                                snapshot.profileFingerprint != state.tip.profileFingerprint,
                            onRefreshTip = onRefreshTip
                        )
                    }

                    is DailyAiTipUiState.Error -> {
                        AiTipErrorBody(
                            messageFa = state.messageFa,
                            onRetry = onRefreshTip
                        )
                    }

                    is DailyAiTipUiState.OfflineDisabled -> {
                        AiTipOfflineDisabledBody(
                            reasonFa = state.reasonFa,
                            onOpenSettings = onOpenConnectivityPrivacySettings
                        )
                    }

                    is DailyAiTipUiState.Idle -> {
                        AiTipIdleBody(onGenerate = onRefreshTip)
                    }
                }
            }
        }
    }
}

@Composable
private fun SpendingSignalPillRow(
    snapshot: SpendingAndDebtSnapshot,
    currencyUnit: CurrencyUnit,
    privacyMasked: Boolean
) {
    val ext = LocalTarazinoColors.current
    val dtiFa = "${PersianCurrencyEngine.toPersianDigits(snapshot.dtiPercent.toString())}٪"
    val dtiColor = when {
        snapshot.dtiPercent >= 45 -> ext.danger
        snapshot.dtiPercent >= 30 -> ext.warning
        else -> ext.positive
    }
    val expenseLabel = if (privacyMasked) {
        "••••"
    } else if (snapshot.totalRecurringNonLoanExpenseToman > 0L) {
        if (currencyUnit == CurrencyUnit.TOMAN) {
            formatCompactPersianToman(snapshot.totalRecurringNonLoanExpenseToman, privacyMasked = false)
        } else {
            PersianCurrencyEngine.formatAmount(snapshot.totalRecurringNonLoanExpenseToman, currencyUnit)
        }
    } else {
        "${PersianCurrencyEngine.toPersianDigits(snapshot.livingExpensePercent.toString())}٪ درآمد"
    }
    val pressureLabel = when {
        snapshot.overdueCount > 0 -> "${PersianCurrencyEngine.toPersianDigits(snapshot.overdueCount.toString())} قسط معوق"
        snapshot.dueNext7DaysCount > 0 -> "${PersianCurrencyEngine.toPersianDigits(snapshot.dueNext7DaysCount.toString())} سررسید هفته"
        else -> "بدون معوقه"
    }
    val pressureColor = when {
        snapshot.overdueCount > 0 -> ext.danger
        snapshot.dueNext7DaysCount > 0 -> ext.warning
        else -> ext.positive
    }

    Row(
        modifier = Modifier.fillMaxWidth(),
        horizontalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        CompactSignalMetricChip(
            label = "نسبت قسط",
            value = dtiFa,
            accent = dtiColor,
            modifier = Modifier.weight(1f)
        )
        CompactSignalMetricChip(
            label = "مخارج جاری",
            value = expenseLabel,
            accent = MaterialTheme.colorScheme.secondary,
            modifier = Modifier.weight(1.15f)
        )
        CompactSignalMetricChip(
            label = "فشار سررسید",
            value = pressureLabel,
            accent = pressureColor,
            modifier = Modifier.weight(1.05f)
        )
    }
}

@Composable
private fun CompactSignalMetricChip(
    label: String,
    value: String,
    accent: Color,
    modifier: Modifier = Modifier
) {
    Surface(
        shape = RoundedCornerShape(13.dp),
        color = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.55f),
        border = BorderStroke(0.75.dp, accent.copy(alpha = 0.28f)),
        modifier = modifier
    ) {
        Column(
            modifier = Modifier.padding(horizontal = 9.dp, vertical = 7.dp),
            verticalArrangement = Arrangement.spacedBy(2.dp)
        ) {
            Text(
                text = label,
                style = MaterialTheme.typography.labelSmall,
                fontSize = 10.sp,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis
            )
            TarazinoAutoSizeText(
                text = value,
                style = MaterialTheme.typography.labelMedium,
                fontWeight = FontWeight.ExtraBold,
                color = accent,
                maxLines = 1,
                minFontSize = 9.sp
            )
        }
    }
}

